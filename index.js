const AUTH_ROOT = 'auth_sessions';

if (!fs.existsSync(AUTH_ROOT)) fs.mkdirSync(AUTH_ROOT, { recursive: true });

const sessions = new Map();
const pairingLocks = new Map();
const rateLimitMap = new Map();

// Rate limiting helper
function checkRate(key, limit, windowMs) {
    limit = limit || 5;
    windowMs = windowMs || 60000;
    const now = Date.now();
    const hits = (rateLimitMap.get(key) || []).filter(t => now - t < windowMs);
    if (hits.length >= limit) return false;
    hits.push(now);
    rateLimitMap.set(key, hits);
    return true;
}

// Per-number lock to prevent duplicate sessions
async function withLock(number, fn) {
    while (pairingLocks.get(number)) {
        await pairingLocks.get(number);
    }
    let release;
    const lockPromise = new Promise(r => release = r);
    pairingLocks.set(number, lockPromise);
    try {
        return await fn();
    } finally {
        pairingLocks.delete(number);
        release();
    }
}

function getSession(number) {
    return sessions.get(number) || null;
}

function setSession(number, data) {
    sessions.set(number, data);
}

function deleteSession(number) {
    const s = sessions.get(number);
    if (s && s.sock) {
        try { s.sock.end(undefined); } catch (e) {}
    }
    sessions.delete(number);
}

// Wait for socket to be ready
function waitForSocketReady(sock, timeoutMs) {
    timeoutMs = timeoutMs || 20000;
    return new Promise((resolve, reject) => {
        const start = Date.now();
        const check = () => {
            const ws = sock.ws;
            if (ws && ws.readyState === 1) return resolve();
            if (Date.now() - start > timeoutMs) return reject(new Error('Socket ready timeout'));
            setTimeout(check, 300);
        };
        check();
    });
}

async function createSession(number) {
    const sessionDir = path.join(AUTH_ROOT, number);
    if (!fs.existsSync(sessionDir)) fs.mkdirSync(sessionDir, { recursive: true });

    const { state, saveCreds } = await useMultiFileAuthState(sessionDir);

    const sock = makeWASocket({
        auth: state,
        printQRInTerminal: false,
        logger: pino({ level: 'silent' }),
        browser: ['Ubuntu', 'Chrome', '20.0.04'],
        connectTimeoutMs: 60000,
        defaultQueryTimeoutMs: 0,
        keepAliveIntervalMs: 10000,
        syncFullHistory: false,
        markOnlineOnConnect: false,
        generateHighQualityLinkPreview: false,
        getMessage: async () => ({})
    });

    const session = {
        number,
        sock,
        isConnected: false,
        pairingCode: null,
        registered: false,
        authState: state,
        reconnectAttempts: 0,
        createdAt: Date.now()
    };
    setSession(number, session);

    sock.ev.on('creds.update', saveCreds);

    sock.ev.on('connection.update', async (update) => {
        const connection = update.connection;
        const lastDisconnect = update.lastDisconnect;

        if (connection === 'open') {
            session.isConnected = true;
            session.pairingCode = null;
            session.registered = !!(state.creds && state.creds.registered);
            session.reconnectAttempts = 0;
            console.log('[OK] ' + number + ' connected');
        }

        if (connection === 'close') {
            session.isConnected = false;
            session.pairingCode = null;
            const statusCode = new Boom(lastDisconnect && lastDisconnect.error ? lastDisconnect.error : undefined).output.statusCode;
            const shouldReconnect = statusCode !== DisconnectReason.loggedOut;
            console.log('[CLOSE] ' + number + ' code: ' + statusCode);

            if (shouldReconnect) {
                session.reconnectAttempts += 1;
                const delay = Math.min(1000 * Math.pow(2, session.reconnectAttempts), 30000);
                setTimeout(() => {
                    if (sessions.has(number)) {
                        try { session.sock.end(undefined); } catch (e) {}
                        createSession(number).catch((err) => console.error('Reconnect failed ' + number + ':', err.message));
                    }
                }, delay);
            } else {
                console.log('[LOGOUT] ' + number);
                deleteSession(number);
            }
        }
    });

    sock.ev.on('messages.upsert', async (payload) => {
        try {
            const messages = payload.messages;
            const m = messages[0];
            if (!m || !m.message) return;
            const from = m.key.remoteJid;
            const text = m.message.conversation || (m.message.extendedTextMessage && m.message.extendedTextMessage.text);
            console.log('[MSG][' + number + '] from ' + from + ': ' + text);

            if (text && text.toLowerCase() === 'ping') {
                try { await sock.sendMessage(from, { text: 'pong' }); } catch (e) {}
            }
        } catch (e) {
            console.error('Message handler error:', e.message);
        }
    });

    return session;
}

app.get('/api/status', (req, res) => {
    const number = req.query.number ? String(req.query.number).replace(/\D/g, '') : null;
    if (number) {
        const s = getSession(number);
        if (!s) return res.json({ connected: false, registered: false, pairingCode: null, exists: false });
        return res.json({
            exists: true,
            connected: s.isConnected,
            registered: !!(s.authState && s.authState.creds && s.authState.creds.registered),
            pairingCode: s.pairingCode,
            number: number
        });
    }

    const all = [];
    sessions.forEach((s, num) => {
        all.push({
            number: num,
            connected: s.isConnected,
            registered: !!(s.authState && s.authState.creds && s.authState.creds.registered)
        });
    });
    res.json({ total: all.length, sessions: all });
});

app.post('/api/pair', async (req, res) => {
    if (!checkRate('pair:' + req.ip, 5, 60000)) {
        return res.status(429).json({ error: 'Too many requests. Please wait 1 minute.' });
    }

    const body = req.body || {};
    const number = body.number;
    if (!number) return res.status(400).json({ error: 'Phone number required' });

    const cleanNumber = String(number).replace(/\D/g, '');
    if (cleanNumber.length < 10 || cleanNumber.length > 15) {
        return res.status(400).json({ error: 'Invalid number. Include country code.' });
    }

    try {
        const result = await withLock(cleanNumber, async () => {
            let session = getSession(cleanNumber);

            if (session && session.authState && session.authState.creds && session.authState.creds.registered) {
                return { status: 'already_connected', message: 'Already paired.', number: cleanNumber };
            }

            if (session) deleteSession(cleanNumber);
            session = await createSession(cleanNumber);

            await waitForSocketReady(session.sock, 20000);

            const code = await session.sock.requestPairingCode(cleanNumber);
            session.pairingCode = code;
            console.log('[PAIR] ' + cleanNumber + ' -> ' + code);

            return { status: 'success', pairingCode: code, phoneNumber: cleanNumber };
        });

        res.json(result);
    } catch (error) {
        console.error('Pair error:', error && error.message ? error.message : error);
        res.status(500).json({ error: 'Failed to get pairing code', detail: error && error.message ? error.message : String(error) });
    }
});

app.post('/api/send', async (req, res) => {
    if (!checkRate('send:' + req.ip, 20, 60000)) {
        return res.status(429).json({ error: 'Too many messages. Please wait.' });
    }

    const body = req.body || {};
    const to = body.to;
    const message = body.message;
    const from = body.from ? String(body.from).replace(/\D/g, '') : null;

    if (!to || !message) return res.status(400).json({ error: 'Both to and message required' });

    let session = null;
    if (from) {
        session = getSession(from);
        if (!session) return res.status(400).json({ error: 'No session for ' + from });
    } else {
        for (const s of sessions.values()) {
            if (s.isConnected) { session = s; break; }
        }
    }

    if (!session || !session.isConnected) {
        return res.status(400).json({ error: 'Not connected. Please pair first.' });
    }

    try {
        const cleanTo = String(to).replace(/\D/g, '');
        if (cleanTo.length < 10 || cleanTo.length > 15) {
            return res.status(400).json({ error: 'Invalid recipient number.' });
        }
        const trimmed = String(message).trim();
        if (!trimmed) return res.status(400).json({ error: 'Message cannot be empty.' });
        if (trimmed.length > 4096) return res.status(400).json({ error: 'Message too long (max 4096 chars).' });

        const jid = cleanTo + '@s.whatsapp.net';
        await session.sock.sendMessage(jid, { text: trimmed });
        res.json({ status: 'sent', to: jid, from: session.number, message: trimmed });
    } catch (error) {
        console.error('Send error:', error && error.message ? error.message : error);
        res.status(500).json({ error: 'Send failed', detail: error && error.message ? error.message : String(error) });
    }
});
