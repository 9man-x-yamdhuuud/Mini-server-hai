async function start() {
    try {
        const dirs = fs.readdirSync(AUTH_ROOT);
        for (const d of dirs) {
            try {
                const stat = fs.statSync(path.join(AUTH_ROOT, d));
                if (stat.isDirectory()) {
                    console.log("[RESTORE] Loading session: " + d);
                    await createSession(d);
                }
            } catch (e) {
                console.error("Restore failed " + d + ":", e.message);
            }
        }
    } catch (e) {
        console.error("Session restore scan failed:", e.message);
    }
    app.listen(PORT, HOST, () => {
        console.log("Noman X Yamdhud server running at http://" + HOST + ":" + PORT);
    });
}

start();
